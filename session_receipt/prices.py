"""Refresh the price reference from OpenRouter's public model list, once, on request.

`session-receipt update-prices` is the ONLY command that touches the network. It downloads
https://openrouter.ai/api/v1/models (or reads a saved copy with --from), and writes, dated:

  pricing/openrouter-snapshot.json  the Anthropic + OpenAI price entries as published
  pricing/reference.json            Claude rates in USD/MTok, used by pricecheck
  pricing/ccusage-overrides.json    ccusage price overrides for any Claude model whose
                                    built-in ccusage rate disagrees with the snapshot

Receipts then cost tokens at the snapshot's prices and print "OpenRouter list as of <date>".
Models with a long-prompt price tier are never overridden (a flat override would erase the
tier); a disagreement there stays visible as a price-check warning instead.
"""
import hashlib
import json
import os
import tempfile
from datetime import datetime, timezone

from . import ccusage_adapter as ad
from . import pricecheck

URL = "https://openrouter.ai/api/v1/models"
PRICING_DIR = os.path.join(ad.ROOT, "pricing")
SNAPSHOT = os.path.join(PRICING_DIR, "openrouter-snapshot.json")
# OpenRouter pricing field -> reference rate key. OpenRouter quotes USD per token.
FIELDS = {"prompt": "input", "completion": "output", "input_cache_write": "cache_write_5m",
          "input_cache_write_1h": "cache_write_1h", "input_cache_read": "cache_read"}


def fetch(url=URL, timeout=30):
    import urllib.request  # the only network use in the package; reached only by update-prices
    req = urllib.request.Request(url, headers={"User-Agent": "session-receipt/0.1"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def _per_mtok(p):
    return {FIELDS[k]: round(float(v) * 1e6, 9) for k, v in p.items() if k in FIELDS}


def reference_key(or_id):
    """'anthropic/claude-sonnet-5.5' -> 'sonnet-5-5' (ccusage model 'claude-sonnet-5-5')."""
    return or_id.split("/", 1)[1].replace("claude-", "", 1).replace(".", "-")


def build_reference(raw, fetched_at):
    models = json.loads(raw)["data"]
    snap, ref = {}, {}
    for m in models:
        mid = m.get("id", "")
        if ":" in mid or not mid.startswith(("anthropic/", "openai/")):
            continue  # skip :batch / :free variants and other providers
        p = m.get("pricing") or {}
        snap[mid] = p
        rates = _per_mtok(p)
        if not mid.startswith("anthropic/claude-") or set(rates) != set(FIELDS.values()):
            continue  # reference needs all five Claude rates
        entry = dict(rates)
        tiers = [dict(min_prompt_tokens=t["min_prompt_tokens"], **_per_mtok(t))
                 for t in p.get("overrides") or [] if "min_prompt_tokens" in t]
        if tiers:
            entry["tiers"] = tiers
        ref[reference_key(mid)] = entry
    day = fetched_at[:10]
    meta = {"source": "OpenRouter list", "url": URL, "as_of": day, "checked": day,
            "fetched_at": fetched_at, "sha256": hashlib.sha256(raw).hexdigest(),
            "unit": "USD per million tokens (MTok)",
            "notes": ["Generated by `session-receipt update-prices`; do not hand-edit.",
                      "OpenRouter passes Anthropic's list prices through; spot-checked against "
                      "docs.claude.com/en/docs/about-claude/pricing on 2026-10-21.",
                      "`tiers` = long-prompt rates; pricecheck probes stay below them."]}
    reference = dict(meta, models=ref)
    snapshot = dict(meta, models=snap)
    return reference, snapshot


def _override_entry(r):
    return {"inputCostPerToken": r["input"] / 1e6, "outputCostPerToken": r["output"] / 1e6,
            "cacheCreationInputTokenCost": r["cache_write_5m"] / 1e6,
            "cacheReadInputTokenCost": r["cache_read"] / 1e6}


def _write_json(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w", newline="\n") as f:
        json.dump(obj, f, indent=1, sort_keys=True)
        f.write("\n")
    os.replace(tmp, path)


def update(raw, fetched_at=None, pricing_dir=PRICING_DIR, log=print):
    fetched_at = fetched_at or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    reference, snapshot = build_reference(raw, fetched_at)
    if not reference["models"]:
        raise ad.ReceiptError("no Claude prices found in the OpenRouter response; nothing written")
    ref_path = os.path.join(pricing_dir, "reference.json")
    ovr_path = os.path.join(pricing_dir, "ccusage-overrides.json")
    _write_json(os.path.join(pricing_dir, "openrouter-snapshot.json"), snapshot)
    _write_json(ref_path, reference)
    # Measure ccusage's built-in rates against the new reference with NO overrides.
    with tempfile.TemporaryDirectory(prefix="sr_up_") as t:
        empty = os.path.join(t, "empty.json")
        _write_json(empty, {"defaults": {"pricingOverrides": {}}})
        overrides, notes = {}, []
        for key, r in sorted(reference["models"].items()):
            res = pricecheck.check_model("claude-" + key, empty, use_cache=False, reference_path=ref_path)
            if res["status"] == "ok":
                continue
            fixable = [k for k in res["differing"] if k != "cache_write_1h"]
            if "tiers" in r:
                notes.append("%s: ccusage differs on %s; has a long-prompt tier, NOT overridden"
                             % (key, ", ".join(res["differing"])))
            elif fixable:
                overrides["claude-" + key] = _override_entry(r)
                notes.append("%s: ccusage differs on %s; overridden" % (key, ", ".join(res["differing"])))
            if "cache_write_1h" in res["differing"]:
                notes.append("%s: 1-hour cache write differs and ccusage cannot override it" % key)
    _write_json(ovr_path, {"defaults": {"pricingOverrides": overrides}})
    log("prices as of %s from %s: %d Claude models, %d override(s)"
        % (reference["as_of"], URL, len(reference["models"]), len(overrides)))
    for n in notes:
        log("  " + n)
    return reference, overrides, notes
